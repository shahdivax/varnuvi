import dev.voiceagent.app.insert.InsertionText

fun main() {
    val replace = InsertionText.merge("Hello world", 6, 11, "Varnuvi")
    check(replace.text == "Hello Varnuvi" && replace.cursor == 13)
    val reverse = InsertionText.merge("abcdef", 4, 2, "X")
    check(reverse.text == "abXef" && reverse.cursor == 3)
    val append = InsertionText.merge("Keep this", -1, -1, " too")
    check(append.text == "Keep this too")
    val invalid = InsertionText.merge("Keep this", 999, 999, "!")
    check(invalid.text == "Keep this!")
    val unicode = InsertionText.merge("A🙂B", 3, 3, "હાય")
    check(unicode.text == "A🙂હાયB" && unicode.cursor == 3 + "હાય".length)
    check(InsertionText.merge("", -1, -1, "Voice").text == "Voice")
    check(InsertionText.merge("Keep", 0, 4, "Replace").text == "Replace")
    check(InsertionText.merge("Unchanged", 4, 4, "").text == "Unchanged")
    check(InsertionText.visible("Text message", "Text message", false) == "")
    check(InsertionText.visible("Text message", "Text message", true) == "")
    check(InsertionText.visible("Hi there", "Text message", false) == "Hi there")
    check(InsertionText.visible("Hint", null, true) == "")
    check(InsertionText.visible("Typed", "", false, 5, 5) == "Typed")
    check(InsertionText.visible(null, "Text message", false) == "")
    val placeholder = InsertionText.visible("Text message", "Text message", false)
    check(InsertionText.merge(placeholder, 12, 12, "Hello").text == "Hello")
    check(InsertionText.visible("Message", null, false, 0, 0) == "")
    check(InsertionText.visible("Message", null, false, -1, -1) == "")
    check(InsertionText.visible("Message", null, false, 7, 7) == "Message")
    check(InsertionText.visible("Escribe un mensaje", null, false, 0, 0) == "")
    check(InsertionText.visible("Hello there", null, false, 11, 11) == "Hello there")
    check(InsertionText.visible("Line one\nline two", null, false, 0, 0) == "Line one\nline two")
    check(InsertionText.visible("x".repeat(60), null, false, 0, 0) == "x".repeat(60))
    check(InsertionText.visible("Draft", "Message", false, 0, 0) == "Draft")
    check(InsertionText.visible("Type a message", "", false, 0, 0) == "")
    println("PASS: placeholder-as-text treated as empty")
    println("PASS: cursor insertion, selected/reversed range replacement, unknown cursor, Unicode, content preservation")
}
